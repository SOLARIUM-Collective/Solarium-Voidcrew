foreach ($failure in @('upload', 'download', 'credentials', 'settings', 'disabled', 'prune')) {
    $script:fixture = New-Fixture $failure
    $script:uploadFails = $failure -eq 'upload'
    $script:downloadFails = $failure -eq 'download'
    $script:pruneFails = $failure -eq 'prune'
    if ($failure -eq 'credentials') { [IO.File]::WriteAllText((Join-Path $fixture.Config 'Secrets/external-rsc-aws.json'), '{BROKEN-SECRET-CANARY') }
    if ($failure -eq 'settings') { [IO.File]::Delete((Join-Path $fixture.Config 'external-rsc.json')) }
    if ($failure -eq 'disabled') { '{"Enabled":false}' | Set-Content (Join-Path $fixture.Config 'external-rsc.json') }
    $messages = @()
    Assert ((Invoke-ExternalRsc Publish $fixture.Deploy $fixture.Root -WarningVariable +messages) -eq 0) "$failure does not fail deployment"
    Assert (($messages -join '') -notmatch 'BROKEN-SECRET-CANARY') 'credential parse errors do not reveal secrets'
    $hasUrl = !!(Select-String $fixture.Resources -Pattern '^EXTERNAL_RSC_URLS')
    Assert ($hasUrl -eq ($failure -eq 'prune')) "$failure fallback/retained URL"
    Assert ([IO.File]::ReadAllText($fixture.Resources).Contains('ASSET_TRANSPORT webroot')) "$failure preserves browser settings"
    Assert (@(Get-ChildItem $fixture.Deploy -Filter '*.zip').Count -eq 0) "$failure temporary cleanup"
}

# Pruning must finish pagination before deleting anything, and only delete this prefix's ZIPs.
$script:deleted = @()
$script:page = 0
$keys = @(1..5 | ForEach-Object { 'external-rsc/test/tgstation-' + $_.ToString('x32') + '.zip' })
function Invoke-S3($Settings, $Credentials, $Method, $Key, $Query) {
    if ($Method -eq 'DELETE') {
        Assert ($script:page -eq 2) 'pagination completes before deletion'
        $script:deleted += $Key
        return ''
    }
    $script:page++
    Assert ($Query.prefix -eq 'external-rsc/test/tgstation-') 'list only instance ZIP prefix'
    if ($script:page -eq 1) { $indexes = @(0, 1, 2); $tail = '<IsTruncated>true</IsTruncated><NextContinuationToken>a+/=</NextContinuationToken>' }
    else {
        Assert ($Query['continuation-token'] -eq 'a+/=') 'pagination token retained'
        $indexes = @(3, 4); $tail = '<IsTruncated>false</IsTruncated>'
    }
    $contents = ($indexes | ForEach-Object { "<Contents><Key>$($keys[$_])</Key><LastModified>2026-09-0$($_ + 1)T00:00:00Z</LastModified></Contents>" }) -join ''
    "<ListBucketResult xmlns='http://s3.amazonaws.com/doc/2006-03-01/'>$contents<Contents><Key>unrelated.zip</Key><LastModified>2000-01-01T00:00:00Z</LastModified></Contents>$tail</ListBucketResult>"
}
Remove-OldResources $settings $credentials @($keys[0], $keys[4])
Assert (($script:deleted -join ',') -ceq ($keys[1..2] -join ',')) 'retain active, published, and newest third build; preserve unrelated objects'
Write-Host "PASS: $script:passed assertions. Fixtures: $fixtureRoot"
